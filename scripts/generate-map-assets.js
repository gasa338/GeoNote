/**
 * Generates src/components/map/generated/*.ts from npm packages:
 *  - leafletAssets.ts : the Leaflet library (JS + CSS) as strings, so the map
 *    works without loading anything from a CDN.
 *  - mapIcons.ts      : a few Ionicons as SVG strings, used for map markers.
 *
 * Run after updating `leaflet` or when you need a new marker icon:
 *   npm run generate:map
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'src/components/map/generated');
fs.mkdirSync(outDir, { recursive: true });

const header = '// ⚠️ GENERATED by scripts/generate-map-assets.js — do not edit by hand.\n';

const js = fs.readFileSync(path.join(root, 'node_modules/leaflet/dist/leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'node_modules/leaflet/dist/leaflet.css'), 'utf8');
fs.writeFileSync(
  path.join(outDir, 'leafletAssets.ts'),
  `${header}/** Leaflet ${require(path.join(root, 'node_modules/leaflet/package.json')).version} (BSD-2-Clause) */\n` +
    `export const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);

// Icons that can be drawn inside map markers. Add a name here and re-run the script.
const ICONS = [
  'basket-outline',
  'person-outline',
  'checkbox-outline',
  'library-outline',
  'storefront-outline',
  'book-outline',
  'location',
];
const icons = {};
for (const name of ICONS) {
  icons[name] = fs.readFileSync(path.join(root, `node_modules/ionicons/dist/svg/${name}.svg`), 'utf8').trim();
}
fs.writeFileSync(
  path.join(outDir, 'mapIcons.ts'),
  `${header}/** Ionicons (MIT) as SVG strings for map markers. */\nexport const MAP_ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n`,
);
console.log('Map assets generated in', path.relative(root, outDir));
